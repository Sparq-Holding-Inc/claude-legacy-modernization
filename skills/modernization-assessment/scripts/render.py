#!/usr/bin/env python3
"""Render graph.json as markdown fact tables. Python standard library only.

    render.py inventory GRAPH.json --out modernization-assessment/01-inventory.md
    render.py edges     GRAPH.json --out modernization-assessment/02a-edge-tables.md
    render.py deadcode  GRAPH.json --out modernization-assessment/05a-dead-code-candidates.md
    render.py waveseed  GRAPH.json --out modernization-assessment/03a-wave-seed.md
    render.py wavedraft GRAPH.json --out modernization-assessment/03a-waves-draft.json

Without --out the markdown goes to standard output.

These tables are facts. Every row of an edge table carries a file:line
citation that came from the extractor, so it resolves by construction. Claude
writes the judgment around them: the patterns, the wave cuts, the risk scores.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import schema  # noqa: E402

PROGRAMS = set(schema.PROGRAM_TYPES)


def cite(evidence, limit=3):
    items = ["`%s:%d`" % (e["file"], e["line"]) for e in evidence[:limit]]
    if len(evidence) > limit:
        items.append("+%d more" % (len(evidence) - limit))
    return ", ".join(items)


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        out.append("| " + " | ".join(cell(x) for x in r) + " |")
    return out


def short(nid):
    return nid


def inventory(g):
    nodes = g["nodes"]
    a = g["analysis"]
    out = ["# 01 Inventory", "",
           "Generated by `render.py` from `graph.json`. These are facts read by the extractor, "
           "not judgments.", "",
           "## Counts", ""]
    out += table(["Unit type", "Count"], sorted(a["node_counts"].items()))
    out += ["", "## Programs", ""]
    rows = []
    for n in nodes:
        if n["unit_type"] in PROGRAMS:
            rows.append([n["id"], n["unit_type"], "`%s`" % n["path"], n["loc"], n.get("last_modified") or "unknown",
                         "yes" if n["entry_point"] else ""])
    out += table(["Program", "Type", "Path", "LOC", "Last modified", "Entry point"], rows)
    out += ["", "## JCL jobs and scheduler artifacts", ""]
    rows = [[n["id"], n["unit_type"], "`%s`" % n["path"] if n.get("path") else "not in tree", n["loc"],
             n.get("last_modified") or "unknown"]
            for n in nodes if n["unit_type"] in ("jcl_job", "scheduler_job")]
    out += table(["Unit", "Type", "Path", "LOC", "Last modified"], rows)
    out += ["", "## Procs, maps and copybooks", ""]
    rows = [[n["id"], n["unit_type"], "`%s`" % n["path"], n["loc"], n.get("last_modified") or "unknown"]
            for n in nodes if n["unit_type"] in ("proc", "map", "copybook")]
    out += table(["Unit", "Type", "Path", "LOC", "Last modified"], rows)
    out += ["", "## Datasets", ""]
    rows = []
    for n in nodes:
        if n["unit_type"] == "dataset":
            rows.append([n["id"][3:], n.get("note", "")])
    out += table(["Dataset", "Note"], rows)
    out += ["", "## Not parsed", ""]
    if g["unparsed"]:
        out += table(["File", "Reason"], [["`%s`" % u["file"], u["reason"]] for u in g["unparsed"]])
    else:
        out.append("Nothing was skipped.")
    out += ["", "## Known limits of the extractor", ""]
    out += ["- " + x for x in g["meta"]["limits"]]
    return "\n".join(out) + "\n"


def edges(g):
    e = g["edges"]
    a = g["analysis"]
    node = {n["id"]: n for n in g["nodes"]}
    out = ["# 02a Edge tables", "",
           "Generated by `render.py` from `graph.json`. Every row cites the source lines the "
           "extractor read. Ordering edges between steps inside one job are listed at the end when there are few. Confidence is high, medium or low. A low row is where a human should look.", "",
           "## Edge counts", ""]
    out += table(["Kind", "Count"], sorted(a["edge_counts"].items()))

    out += ["", "## Contract edges", "",
            "Writer to reader through a dataset. The record layout is an undocumented API. "
            "High means both sides use the same layout copybook. Medium means the layouts differ or are unknown.", ""]
    contracts = [x for x in e if x["kind"] == "contract"]
    if len(contracts) > 100:
        groups = {}
        for x in contracts:
            g = groups.setdefault(x["note"].split(":")[0], {"w": set(), "r": set(), "conf": set(), "ev": x["evidence"]})
            g["w"].add(x["src"])
            g["r"].add(x["dst"])
            g["conf"].add(x["confidence"])
        rows = [[ds, len(g["w"]), len(g["r"]), ", ".join(sorted(g["conf"])), cite(g["ev"], 2)]
                for ds, g in sorted(groups.items(), key=lambda kv: -(len(kv[1]["w"]) * len(kv[1]["r"])))]
        out += ["%d writer to reader pairs, grouped by dataset. Every pair is in `graph.json`." % len(contracts), ""]
        out += table(["Dataset", "Writers", "Readers", "Confidence", "Evidence"], rows)
    else:
        rows = [[x["src"], x["dst"], x["confidence"], x["note"], cite(x["evidence"])] for x in contracts]
        out += table(["Writer", "Reader", "Confidence", "Note", "Evidence"], rows)

    out += ["", "## Data hubs", "",
            "Datasets with the most programs attached. Ordering constraint: every writer runs before its readers.", ""]
    rows = []
    for h in a["data_hubs"]:
        ev = next((x["evidence"] for x in e if x["kind"] == "data" and x["dst"] == h["id"]), [])
        rows.append([h["id"][3:], h["writers"], h["readers"], cite(ev, 2)])
    out += table(["Dataset", "Writers", "Readers", "Evidence"], rows)

    out += ["", "## Program to program calls", "",
            "In-tree programs only. Calls to system programs are in the graph but left out here.", ""]
    rows = [[x["src"], x["dst"], x["confidence"], x["note"], cite(x["evidence"])]
            for x in e if x["kind"] == "call" and node.get(x["src"], {}).get("unit_type") in PROGRAMS
            and node.get(x["dst"], {}).get("unit_type") in PROGRAMS]
    out += table(["Caller", "Callee", "Confidence", "Note", "Evidence"], rows)

    out += ["", "## Ordering enforced by schedulers and wrappers", ""]
    rows = [[x["src"], x["dst"], x["confidence"], x["note"], cite(x["evidence"])]
            for x in e if x["kind"] == "temporal" and not x["src"].startswith("step:")]
    out += table(["Before", "After", "Confidence", "Note", "Evidence"], rows)
    n_steps = sum(1 for x in e if x["kind"] == "temporal" and x["src"].startswith("step:"))
    steps = [x for x in e if x["kind"] == "temporal" and x["src"].startswith("step:")]
    if 0 < len(steps) <= 60:
        out += ["", "Step order inside single JCL jobs:", ""]
        out += table(["Before", "After", "Evidence"], [[x["src"], x["dst"], cite(x["evidence"])] for x in steps])
    elif steps:
        out += ["", "%d further ordering edges are step order inside single JCL jobs. They are in `graph.json`." % n_steps]

    out += ["", "## Unresolved computed calls", "",
            "The extractor could not resolve these statically. Any program without a static caller could be "
            "the target. This is the honest boundary of the analysis.", ""]
    rows = []
    for x in e:
        if x["kind"] == "call" and schema.is_dynamic(x["dst"]):
            rows.append([x["src"], x["dst"], x["note"], cite(x["evidence"], 1)])
    out += table(["Caller", "Node", "Note", "Evidence"], rows)

    out += ["", "## Data reached through unmapped or computed names", ""]
    rows = [[x["src"], x["dst"], x["mode"], x["note"], cite(x["evidence"])]
            for x in e if x["kind"] == "data" and not x["resolved"]]
    out += table(["Program", "Dataset node", "Mode", "Note", "Evidence"], rows)

    out += ["", "## Structure computed from the call graph", ""]
    out += table(["Fact", "Units"], [
        ["Strongly connected components (move together or not at all)", "; ".join(", ".join(c) for c in a["sccs"]) or "none"],
        ["Self recursive programs", ", ".join(a["self_recursive"]) or "none"],
        ["Articulation points (candidate wave boundaries)", ", ".join(a["articulation_points"]) or "none"],
        ["God modules (top decile fan-in and fan-out)", ", ".join(a["god_modules"]) or "none"],
    ])
    out += ["", "Fan-in leaders:", ""]
    top = sorted(a["fan_in"].items(), key=lambda kv: (-kv[1], kv[0]))[:10]
    out += table(["Program", "Callers", "Calls out to"], [[k, v, a["fan_out"].get(k, 0)] for k, v in top])
    if a["unscheduled_jobs"]:
        out += ["", "## JCL jobs no scheduler in the tree runs", "",
                "%d of the jobs are not named by any parsed scheduler. They may be run by hand, by an unparsed "
                "scheduler, or not at all." % len(a["unscheduled_jobs"]), ""]
        out += ["- " + j for j in a["unscheduled_jobs"]]
    return "\n".join(out) + "\n"


def deadcode(g):
    a = g["analysis"]
    node = {n["id"]: n for n in g["nodes"]}
    cand = a["dead_code_candidates"]
    out = ["# 05a Dead code candidates", "",
           "Generated by `render.py` from `graph.json`. Three buckets, never two.", "",
           "- **Unreachable**: no static path from any entry point, and no reachable code makes a computed call.",
           "- **Unknown**: not reached statically, but a computed call in reachable code could target it. "
           "Do not delete on this evidence.",
           "- **Dormant**: reachable on paper, not modified for %d years (as of %s). Instrument, do not delete." %
           (a["dormant_years"], a["as_of"]), ""]
    for w in a["warnings"]:
        out += ["> Warning: " + w, ""]
    for bucket in ("unreachable", "unknown", "dormant"):
        out += ["## " + bucket.capitalize(), ""]
        rows = []
        for nid in cand[bucket]:
            n = node[nid]
            loc = "`%s:%d`" % (n["path"], n.get("line", 1)) if n.get("path") else "not in tree"
            rows.append([nid, n["unit_type"], n.get("last_modified") or "unknown", a["dead_code_reasons"].get(nid, ""), loc])
        out += table(["Unit", "Type", "Last modified", "Reason", "Evidence"], rows)
        out.append("")
    out += ["## Computed calls that keep the unknown bucket open", ""]
    rows = [[d["src"], d["dst"], "`%s:%d`" % (d["evidence"]["file"], d["evidence"]["line"])] for d in a["unresolved_dynamic"]]
    out += table(["Caller", "Node", "Evidence"], rows)
    return "\n".join(out) + "\n"


def waveseed(g):
    seed = g["analysis"]["wave_seed"]
    out = ["# 03a Wave seed", "",
           "Generated by `render.py` from `graph.json`. This is a first cut of the waves from facts alone. "
           "It does not judge risk. Every entry point is put in one family by four tests in order: it touches "
           "DB2, IMS or MQ; it writes a dataset a different entry point also uses; it is online or batch; it runs "
           "an application program or none. A unit used by several entry points moves with the earliest family "
           "that uses it. A scheduler job moves with the last family among the jobs it runs. A call cycle "
           "always moves whole.", "",
           "`03a-waves-draft.json` holds the same plan in the shape of `waves.json`.", ""]
    rows = []
    for w in seed["waves"]:
        rows.append([w["wave"], w["family"], len(w["units"]), len(w["entry_points"]), cite(w["evidence"])])
    out += table(["Wave", "Family", "Units", "Entry points", "Evidence"], rows) + [""]
    for w in seed["waves"]:
        shown = w["units"][:80]
        more = " (+%d more in the draft)" % (len(w["units"]) - 80) if len(w["units"]) > 80 else ""
        out += ["## Wave %d. %s" % (w["wave"], w["family"]), "", w["description"] + ".", "",
                ", ".join("`%s`" % u for u in shown) + more, ""]
        if w.get("computed_calls"):
            out += ["Computed calls in this wave, so its confidence cannot be high: " +
                    ", ".join("`%s`" % u for u in w["computed_calls"]) + ".", ""]
    out += ["## Not placed", ""]
    if seed["unassigned"]:
        out += table(["Unit", "Reason"], [[u["id"], u["reason"]] for u in seed["unassigned"]])
    else:
        out.append("Every unit is placed.")
    return "\n".join(out) + "\n"


def wavedraft(g):
    seed = g["analysis"]["wave_seed"]
    waves = [{"wave": w["wave"], "family": w["family"], "name": None, "units": w["units"], "rationale": None,
              "unblocks": None, "blast_radius": None, "confidence": None, "evidence": w["evidence"]}
             for w in seed["waves"]]
    return json.dumps({"target_state": None, "waves": waves, "unassigned": seed["unassigned"]}, indent=1) + "\n"


def main(argv):
    args = argv[1:]
    out = None
    if "--out" in args:
        i = args.index("--out")
        out = args[i + 1] if i + 1 < len(args) else None
        args = args[:i] + args[i + 2:]
    if len(args) != 2 or args[0] not in ("inventory", "edges", "deadcode", "waveseed", "wavedraft") or ("--out" in argv and not out):
        print(__doc__)
        return 2
    with open(args[1], encoding="utf-8") as fh:
        g = json.load(fh)
    text = {"inventory": inventory, "edges": edges, "deadcode": deadcode, "waveseed": waveseed,
            "wavedraft": wavedraft}[args[0]](g)
    if out:
        with open(out, "w", encoding="utf-8") as fh:
            fh.write(text)
        print("wrote %s (%d bytes)" % (out, len(text.encode("utf-8"))))
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
