#!/usr/bin/env python3
"""Build evals/RESULTS.md from the scorecards. Python standard library only.

    python3 evals/render_results.py

Reads evals/scorecard/*.json. Runs the two test scripts and `claude plugin validate`
to get their current status. Writes evals/RESULTS.md. Nothing in RESULTS.md is typed by
hand except the notes in NOTES below, and those say where a number needs care.
"""

import datetime
import json
import os
import platform
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PLUGIN = os.path.dirname(HERE)
KINDS = ("call", "include", "data", "contract", "temporal")


def load(name):
    try:
        return json.load(open(os.path.join(HERE, "scorecard", name)))
    except (OSError, ValueError):
        return None


def run(cmd, cwd=PLUGIN):
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=cwd)
    return r.returncode, (r.stdout + r.stderr).strip()


def prf(s):
    p = s["tp"] / (s["tp"] + s["fp"]) if (s["tp"] + s["fp"]) else 1.0
    r = s["tp"] / (s["tp"] + s["fn"]) if (s["tp"] + s["fn"]) else 1.0
    return p, r


def pct(x):
    return "n/a" if x is None else "%.1f%%" % (100 * x)


def passed_of(text):
    m = re.search(r"(\d+) of (\d+) passed", text)
    return (int(m.group(1)), int(m.group(2))) if m else (0, 0)


def validate_all():
    targets = [(".", "marketplace"), (".claude-plugin/plugin.json", "plugin manifest, which also checks hooks/hooks.json"),
               ("skills", "skills"), ("agents", "agents"), ("commands", "commands")]
    out = []
    for path, label in targets:
        rc, text = run(["claude", "plugin", "validate", path, "--strict"])
        out.append((label, rc == 0, text.splitlines()[-1] if text else ""))
    return out


def main():
    ext = load("extractor.json")
    mut = load("mutation.json")
    e2e = load("e2e.json")
    _, ver = run(["claude", "--version"])
    hook_rc, hook_out = run([sys.executable, os.path.join(HERE, "test_hook.py")])
    sc_rc, sc_out = run([sys.executable, os.path.join(HERE, "test_e2e_metrics.py")])
    va_rc, va_out = run([sys.executable, os.path.join(HERE, "test_validators.py")])
    wq_rc, wq_out = run([sys.executable, os.path.join(HERE, "test_wave_quality.py")])
    val = validate_all()
    L = []
    w = L.append
    w("# Results")
    w("")
    w("Generated by `evals/render_results.py` on %s. Do not edit by hand." % datetime.date.today().isoformat())
    w("")
    w("**Status: candidate build. Every CardDemo number below is PROVISIONAL.** The answer key for CardDemo "
      "was labeled by Claude subagents and has not been confirmed by a domain reviewer. Read "
      "`carddemo/LABELING.md` and `carddemo/ADJUDICATION.md`.")
    w("")
    w("Environment: Python %s, Claude Code %s, CardDemo commit `59cc6c2f`." % (platform.python_version(), ver))
    w("")
    w("## Scorecard against the ship bar")
    w("")
    w("| Level | Metric | Bar | Result | Status |")
    w("|---|---|---|---|---|")
    fx = ext["fixtures"] if ext else None
    cd = ext.get("carddemo") if ext else None
    if fx:
        ok = all(prf(fx["per_kind"][k]) == (1.0, 1.0) for k in KINDS) and fx["all_pass"]
        n = len(fx["cases"])
        w("| Extractor, fixtures | Precision and recall, every edge kind | 100%% | %d of %d fixtures pass. "
          "Every kind 100%% | %s |" % (sum(r["pass"] for r in fx["cases"].values()), n, "PASS" if ok else "FAIL"))
    if cd:
        for k in ("call", "include", "data"):
            p, r = prf(cd["stats"][k])
            w("| Extractor, CardDemo | %s edges, precision and recall vs draft truth | 95%%+ | P %s, R %s | %s |" %
              (k, pct(p), pct(r), "PASS (provisional)" if p >= .95 and r >= .95 else "FAIL"))
        for k in ("contract", "temporal"):
            p, r = prf(cd["stats"][k])
            w("| Extractor, CardDemo | %s edges, recall vs draft truth | 75%%+, reported as is | R %s (P %s) | %s |" %
              (k, pct(r), pct(p), "PASS (provisional)" if r >= .75 else "FAIL"))
    s = e2e["summary"] if e2e else None
    if s and s["runs_scored"]:
        harness = sorted({r.get("harness", "claude -p") for r in e2e["runs"] if r.get("ran")})
        cit = s["citations"]
        w("| End to end | Citations that resolve | 100%% | %s (%d of %d) | %s |" %
          (pct(cit["resolve_rate"]), cit["total"] - cit["unresolved"], cit["total"],
           "PASS" if cit["unresolved"] == 0 else "FAIL"))
        w("| End to end | Unreachable claims on dynamic call targets | 0 | %d | %s |" %
          (s["unreachable_on_dynamic_total"], "PASS" if s["unreachable_on_dynamic_total"] == 0 else "FAIL"))
        cw = s.get("carddemo_waves")
        if cw:
            w("| End to end | Wave count across CardDemo runs (repeatability, not plan quality) | Identical | %s | %s |" %
              (cw["wave_counts"], "PASS" if cw["wave_count_identical"] else "FAIL"))
            w("| End to end | Pairwise wave co-assignment across CardDemo runs (repeatability, not plan quality) | 80%%+ | Jaccard of co-assigned pairs %s. "
              "Rand index %s. Unit overlap %s%s | %s |" %
              (pct(cw["jaccard"]), pct(cw["rand_index_mean"]), pct(cw["unit_overlap"]),
               (". Deviations from the extractor's wave seed, per run: %s. Each run's Jaccard with the seed: %s" %
                (cw["deviations"], ", ".join(pct(x) for x in cw["seed_jaccard"])))
               if cw.get("seed_jaccard") else "",
               "PASS" if cw["jaccard"] >= .8 else "FAIL"))
        else:
            w("| End to end | Wave count and co-assignment across CardDemo runs | Identical, 80%+ | NOT RUN | NOT RUN |")
        w("| End to end | graph.json is what the extractor produces (Claude did not edit the facts) | Integrity check | %d of %d runs identical | %s |" %
          (s.get("graph_unmodified_runs", 0), s["runs_scored"], "PASS" if s.get("graph_unmodified_runs", 0) == s["runs_scored"] else "FAIL"))
        w("| End to end | Every JSON output validates | 100%% | %d of %d runs have all four files valid | %s |" %
          (s["json_all_valid_runs"], s["runs_scored"], "PASS" if s["json_all_valid_runs"] == s["runs_scored"] else "FAIL"))
        w("| End to end | Cost and wall time per CardDemo run | Published, no bar | See the run table | INFO |")
        w("| End to end | How the runs were produced | | %s | INFO |" % ", ".join(harness))
    else:
        w("| End to end | Citations, dynamic targets, waves, JSON validity, cost | see plan | NOT RUN | NOT RUN |")
    for label, ok, last in val:
        w("| Packaging | `claude plugin validate --strict` on the %s | Clean | %s | %s |" %
          (label, last.replace("|", "/") or "no output", "PASS" if ok else "FAIL"))
    w("")
    if fx:
        w("## Extractor: seeded fixtures")
        w("")
        w("Truth for fixtures 1 to 25 was written by hand before the extractor existed. For 26 to 29 the edges were reviewed by hand against the source, and the new expectations (wave seed, dead code, facts) were written before the code that computes them. Each fixture is one trap. Matching is on source, "
          "destination, kind and mode. A fixture passes only when confidence, the resolved flag, the evidence "
          "lines, node types, entry points, dates and dead code buckets also match.")
        w("")
        w("| Kind | Precision | Recall | TP | FP | FN |")
        w("|---|---|---|---|---|---|")
        for k in KINDS:
            p, r = prf(fx["per_kind"][k])
            t = fx["per_kind"][k]
            w("| %s | %s | %s | %d | %d | %d |" % (k, pct(p), pct(r), t["tp"], t["fp"], t["fn"]))
        w("")
        w("Evidence lines that resolve to a real file and line: %d of %d." % tuple(fx["evidence_resolves"]))
        w("")
        w("| Fixture | Result | Edges in truth |")
        w("|---|---|---|")
        for c, r in fx["cases"].items():
            w("| %s | %s | %d |" % (c, "pass" if r["pass"] else "FAIL", r["edges"]))
        w("")
    if cd:
        w("## Extractor: AWS CardDemo (draft truth, provisional)")
        w("")
        w("Extraction time: %.1f seconds (bar: under 60). Graded scope: the core application folders. The three "
          "optional IMS, DB2 and MQ extensions are read but not scored, because the plugin does not claim them." %
          cd["seconds"])
        w("")
        w("| Kind | Precision | Recall | TP | FP | FN | Evidence overlaps truth |")
        w("|---|---|---|---|---|---|---|")
        eo = cd["evidence_overlap_with_truth"]
        for k in KINDS:
            p, r = prf(cd["stats"][k])
            t = cd["stats"][k]
            w("| %s | %s | %s | %d | %d | %d | %d of %d |" % (k, pct(p), pct(r), t["tp"], t["fp"], t["fn"],
                                                              eo.get(k + ":overlap", 0), eo.get(k + ":total", 0)))
        w("")
        w("- Entry programs from the CSD match the truth: %s." % cd["entry_programs"]["match"])
        w("- CA-7 listing reported as not parsed: %s." % cd["ca7_reported_unparsed"])
        w("- Every evidence line resolves: %d of %d." % tuple(cd["evidence_resolves"]))
        w("- Computed calls left unresolved, by design: %d." % cd["unresolved_dynamic"])
        w("- Dead code candidates over the whole tree: %s." % cd["dead_code_counts"])
        w("")
        w("### Read these numbers with care")
        w("")
        w("1. **The labelers and the extractor share definitions.** Both follow `carddemo/LABELING.md`. A high "
          "score shows the extractor applies the rules as a careful reader does. It does not show the rules are right.")
        w("2. **The truth was labeled by Claude.** Two independent passes per COBOL partition agreed on nearly every "
          "edge. That does not rule out a shared blind spot.")
        w("3. **Contract edges are derived** from labeled data edges and layout copybooks by rule, so contract "
          "recall largely tests the join logic.")
        w("4. **The extractor found one real gap on this benchmark**, a `COPY 'MEMBER'` with the name in quotes. It was "
          "fixed and fixture 17 was added. No truth file was edited to get here.")
        w("")
    if mut:
        w("## Can the fixtures fail?")
        w("")
        eq = sum(1 for m in mut["mutations"] if m["equivalent"])
        w("`evals/mutation_check.py` breaks the extractor in %d ways and lists the fixtures that notice. "
          "%d caught, %d equivalent (no behavior change), %d not caught." %
          (len(mut["mutations"]), len(mut["mutations"]) - eq - len(mut["blind_spots"]), eq, len(mut["blind_spots"])))
        w("")
        w("| Mutation | Caught by fixtures |")
        w("|---|---|")
        for m in mut["mutations"]:
            w("| %s | %s |" % (m["mutation"], ", ".join(m["caught_by"]) or ("equivalent mutant" if m["equivalent"] else "NOT CAUGHT")))
        w("")
    a, b = passed_of(hook_out)
    c, d = passed_of(sc_out)
    e_, f_ = passed_of(va_out)
    g_, h_ = passed_of(wq_out)
    w("## Tests for the checking code")
    w("")
    w("| Suite | Result |")
    w("|---|---|")
    w("| Citation hook (`test_hook.py`) | %d of %d pass |" % (a, b))
    w("| End to end scorer (`test_e2e_metrics.py`) | %d of %d pass |" % (c, d))
    w("| Output validators, wrong assessments must be rejected (`test_validators.py`) | %d of %d pass |" % (e_, f_))
    w("| Wave quality checks, bad plans must score worse (`test_wave_quality.py`) | %d of %d pass |" % (g_, h_))
    w("")
    if s and s["runs_scored"]:
        w("## End to end runs")
        w("")
        w("| Run | Harness | Turns | Wall or model time | Cost or tokens | Citations | JSON | Waves | Hook gave up |")
        w("|---|---|---|---|---|---|---|---|---|")
        for r in e2e["runs"]:
            if not r.get("ran"):
                w("| %s | not run | | | | | | | |" % r["run"])
                continue
            cl = r["claude"]
            su = r.get("subagent_usage") or {}
            timing = ("%.0fs" % cl["wall_seconds"]) if cl.get("wall_seconds") else (
                ("%.0fs (agent)" % (su["duration_ms"] / 1000)) if su.get("duration_ms") else "n/a")
            cost = ("$%.2f" % cl["total_cost_usd"]) if cl.get("total_cost_usd") is not None else (
                ("%d tokens" % su["tokens"]) if su.get("tokens") else "n/a")
            turns = cl.get("num_turns") or su.get("tool_uses") or "n/a"
            ci = r["citations"]
            w("| %s | %s | %s | %s | %s | %d of %d resolve | %s | %s | %s |" %
              (r["run"], r["harness"], turns, timing, cost, ci["total"] - ci["unresolved"], ci["total"],
               "valid" if r["json_all_valid"] else "INVALID", r.get("wave_count", "n/a"),
               "yes" if r["hook_gave_up"] else "no"))
        w("")
    lp = load("e2e-loops.json")
    if lp and lp.get("loops"):
        w("## Fix loops for the wave metrics")
        w("")
        w(lp["note"])
        w("")
        w("| Loop | Plugin commit | What changed | Wave counts | Jaccard | Rand | Unit overlap | Result |")
        w("|---|---|---|---|---|---|---|---|")
        for lo in lp["loops"]:
            ok = lo["wave_count_identical"] and lo["jaccard"] >= .8
            w("| %d | `%s` | %s | %s | %s | %s | %s | %s |" %
              (lo["loop"], lo["plugin_commit"], lo["what_changed"], lo["wave_counts"], pct(lo["jaccard"]),
               pct(lo["rand_index"]), pct(lo["unit_overlap"]), "PASS" if ok else "FAIL"))
        w("")
        for lo in lp["loops"]:
            w("- Loop %d: %s" % (lo["loop"], lo["diagnosis"]))
        w("")
    wq = load("wave-quality.json")
    if wq and wq.get("rows"):
        w("## Wave quality (separate from repeatability)")
        w("")
        w("Repeatability asks whether runs make the same plan. These ask whether the plan cuts the coupling the "
          "extractor found in sensible places. All of it is computed from the extracted graph, so it checks a plan "
          "against the facts. It does not check the facts, and it does not prove a wave is safe to ship. "
          "`evals/wave_quality.py` explains each metric.")
        w("")
        w("| Loop | Cut better than random plans (lowest of 3 runs) | Units with more links elsewhere (mean) | Order vs blast radius (mean rank correlation) | Waves |")
        w("|---|---|---|---|---|")
        for lp_ in sorted({r_["loop"] for r_ in wq["rows"]}):
            rs = [r_ for r_ in wq["rows"] if r_["loop"] == lp_]
            cp = [r_["cut_percentile"] for r_ in rs if r_["cut_percentile"] is not None]
            mis = [r_["misplaced_share"] for r_ in rs]
            od = [r_["order_spearman"] for r_ in rs if r_["order_spearman"] is not None]
            w("| %d | %s | %s | %s | %s |" % (lp_, pct(min(cp)) if cp else "n/a", pct(sum(mis) / len(mis)),
                                            "%.2f" % (sum(od) / len(od)) if od else "n/a", [r_["waves"] for r_ in rs]))
        w("")
        w("- The cut bar (better than 95% of random plans) was written before any plan was scored. Every plan passes it, "
          "including loop 0, where the runs agreed only 15%. It is a sanity floor. It cannot tell a good cut from a "
          "mediocre one, so I added the misplaced unit count, which can.")
        w("- Units with more links into another wave than into their own fell from about 21% in loop 0 to about 11% in "
          "loop 3. Some of that is real. Some is the seed following its own rules. Wave order against blast radius "
          "improved a little and stays weak.")
        w("- In CardDemo the scheduler chain and medium confidence contract checks have almost nothing to measure "
          "(one giant chain, no medium contract between units), so they say nothing here.")
        w("")
    rh = load("real-harness-trials.json")
    if rh:
        w("## The real headless harness, one fixture")
        w("")
        w(rh["note"])
        w("")
        w("| Cap | Outcome | Cost | Turns | Permission denials |")
        w("|---|---|---|---|---|")
        for t_ in rh["trials"]:
            w("| $%.0f | %s | $%.2f | %d | %d |" % (t_["cap_usd"], t_["outcome"], t_["cost_usd"], t_["turns"], t_["permission_denials"]))
        w("")
        for t_ in rh["trials"]:
            for v_ in t_["verified"]:
                w("- Verified live: " + v_ + ".")
        w("- " + rh["cost_lesson"])
        w("")
    prov = load("e2e-provenance.json")
    if prov and s and s["runs_scored"]:
        w("## How the end to end runs were produced")
        w("")
        w(prov["why"])
        w("")
        w("- Date: %s. Plugin commit when the runs started: `%s`. Model: %s." %
          (prov["date"], prov["plugin_commit_at_start"], prov["model"]))
        w("- **Not exercised by this harness:**")
        for x in prov["not_exercised"]:
            w("  - " + x)
        w("- %s" % prov["changes_during_runs"])
        w("- To replace these with real headless runs: `%s`" % prov["rerun"])
        w("")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    text = main()
    with open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote evals/RESULTS.md (%d bytes)" % len(text.encode("utf-8")))
